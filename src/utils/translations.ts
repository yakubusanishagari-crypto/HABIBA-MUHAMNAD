export const getLocalizedText = (
  lang: Language,
  key: keyof typeof TRANSLATIONS['en']
): string => {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en'][key] || '';
};

// Dynamic product helper
export const getLocalizedProductName = (product: { name: string; name_en?: string; name_ha?: string; name_ar?: string }, lang: Language): string => {
  if (lang === 'ha' && product.name_ha) return product.name_ha;
  if (lang === 'ar' && product.name_ar) return product.name_ar;
  if (product.name_en) return product.name_en;
  return product.name;
};

